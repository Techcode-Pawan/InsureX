// Helper to check existing total allocation for a policy
export function getPolicyTotalAllocation(beneficiaries, policyId, excludeBeneficiaryId = null) {
  return beneficiaries
    .filter(b => b.policyId === policyId && b.beneficiaryId !== excludeBeneficiaryId)
    .reduce((sum, b) => sum + Number(b.allocation || 0), 0)
}
