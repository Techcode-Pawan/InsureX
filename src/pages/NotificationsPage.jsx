import { useState } from 'react'
import { Link } from 'react-router-dom'
import api from '../services/apiClient'
import { useApi } from '../lib/useApi'
import { timeAgo, dateTime } from '../lib/format'
import { PageHead, Panel, DataState, Pager, Segmented } from '../components/panel'
import Button from '../components/ui/Button'

// Full notification history for the signed-in user (any role). Server filters by user id.
export default function NotificationsPage() {
  const [page, setPage] = useState(1)
  const [filter, setFilter] = useState('all')
  const { data, body, loading, error, reload } = useApi('/notifications', { page, limit: 20, unread: filter === 'unread' ? 'true' : undefined })

  async function markAll() {
    await api.post('/notifications/read-all')
    reload()
  }
  async function markOne(n) {
    if (!n.readAt) await api.post(`/notifications/${n.id}/read`).catch(() => {})
  }

  return (
    <div className="px-page" style={{ maxWidth: 820 }}>
      <PageHead
        title="Notifications"
        sub="Updates generated by activity on your records: applications, policies, payments, claims and renewals."
        actions={body?.unread > 0 && <Button variant="secondary" size="sm" onClick={markAll}>Mark all as read</Button>}
      />
      <Panel
        flush
        title={body ? `${body.unread} unread` : 'Loading'}
        action={<Segmented label="Filter notifications" value={filter} onChange={(v) => { setFilter(v); setPage(1) }} options={[{ value: 'all', label: 'All' }, { value: 'unread', label: 'Unread' }]} />}
      >
        <DataState loading={loading} error={error} onRetry={reload} empty={data?.length === 0} emptyText="No notifications yet.">
          <ul className="rows">
            {data?.map((n) => (
              <li key={n.id}>
                <Link to={n.link || '#'} className={`row notif-item ${n.readAt ? '' : 'unread'}`} onClick={() => markOne(n)} style={{ display: 'flex' }}>
                  <div className="row-main">
                    <div className="row-title" style={{ whiteSpace: 'normal' }}>{n.title}</div>
                    <div className="notif-msg">{n.message}</div>
                  </div>
                  <div className="row-end muted" style={{ fontSize: 12 }} title={dateTime(n.createdAt)}>{timeAgo(n.createdAt)}</div>
                </Link>
              </li>
            ))}
          </ul>
          <Pager body={body} page={page} onPage={setPage} />
        </DataState>
      </Panel>
    </div>
  )
}
